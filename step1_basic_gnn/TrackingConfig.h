namespace gnn {

struct TrackingConfig {
    // ゲート半径 [px]。前フレームの点からこの距離を超える最明点は候補にしない。
    //   目安：1フレームあたりの最大移動量 + 観測ノイズの 3σ 程度
    double gateDistance = 30.0;

    // 未検出コスト：前フレームの点に対応する最明点がない場合のコスト [px]
    double missCost = 15.0;

    // 未割り当て観測コスト：今回の最明点がどの点にも対応しない場合のコスト [px]
    //   ※ 割り当ての判断に効くのは missCost + falseAlarmCost の和だけである。
    //     距離 d の組は d < missCost + falseAlarmCost のときに限り
    //     「両方を未割り当てにする」より有利になる。
    //     和をゲート半径と同じにしておくと、ゲートと整合した判断になる。
    double falseAlarmCost = 15.0;
};

}  // namespace gnn
