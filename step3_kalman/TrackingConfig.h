// TrackingConfig.h（STEP 3）
//   STEP 2 の α-β パラメータとユークリッド距離ゲートを、
//   カルマンフィルタの雑音パラメータとカイ二乗ゲートに置き換える。
// ============================================================================

#include <cmath>

namespace gnn {

struct TrackingConfig {
    // ---- 対応付け ----【STEP 3 で変更】
    // ゲートに含める確率 P_G。真の観測がゲート内に入る確率を表す。
    //   観測が2次元のとき、マハラノビス距離の二乗 d² は自由度2のカイ二乗分布に従う。
    //   ※ 資料の 0.99（閾値 9.21）だと、正しい観測でも 1 フレームあたり 1% の確率でゲート外になり、
    //     2目標×30フレームでは約45%の確率でどこかで1回外れる。外れた観測から新しいトラックが
    //     生成されてトラックが分裂しやすいため、ここでは 0.999（閾値 13.82）とした。
    double gateProbability = 0.999;

    // 未検出コスト・未割り当て観測コスト（単位はマハラノビス距離の二乗 d²、無次元）
    //   d² < missCost + falseAlarmCost の組だけが割り当ての対象になる。
    //   和をゲート閾値（0.999 なら 13.82）と同じにしておく。
    double missCost = 6.908;
    double falseAlarmCost = 6.908;

    // ---- カルマンフィルタ ----【STEP 3 で追加】
    // プロセスノイズのスペクトル密度 q [px²/s³]（加速度の白色雑音の強さ）
    //   大きいほど運動モデルからのずれ（加減速・旋回）を許容し、ゲートも広がる。
    double processNoiseDensity = 200.0;
    // 観測ノイズの標準偏差 σ_r [px]（最明点の位置の誤差）
    double measurementNoiseStd = 1.0;
    // 新規トラックの初期速度の標準偏差 [px/s]（速度が未知であることを表す）
    double initialVelocityStd = 100.0;

    // ---- トラック管理（STEP 2 と同じ）----
    int confirmHits = 3;
    int confirmWindow = 5;
    int maxCoastingFrames = 5;

    // 自由度2のカイ二乗分布の上側点（ゲート閾値）
    //   自由度2のカイ二乗分布は平均2の指数分布なので、累積分布関数は
    //     F(x) = 1 − exp(−x/2)
    //   これを解くと閾値 = −2·ln(1 − P_G)。P_G = 0.99 → 9.2103, 0.999 → 13.8155
    //   （自由度が2以外の場合はこの式は使えないため、表や数値計算で求める）
    double gateThreshold() const { return -2.0 * std::log(1.0 - gateProbability); }
};

}  // namespace gnn
